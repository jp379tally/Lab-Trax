  describe("POST /api/send-case-update-text", () => {
    async function caseNumberFor(caseId: string): Promise<string> {
      const { db, cases: casesTable } = dbMod as any;
      const [row] = await db
        .select({ caseNumber: casesTable.caseNumber })
        .from(casesTable)
        .where(eq(casesTable.id, caseId));
      return row.caseNumber;
    }

    it("requires lab case access and sends only to the provider's stored phone", async () => {
      const { sendSms } = await import("../lib/sms.js");
      const sendSmsMock = vi.mocked(sendSms);
      sendSmsMock.mockClear();
      const caseNumber = await caseNumberFor(caseAId);
      const labSession = await makeSession(labOwnerId);

      const forgedDestination = await request(appMod.default)
        .post("/api/send-case-update-text")
        .set("Authorization", `Bearer ${labSession.access}`)
        .send({
          providerPhone: "+15550000099",
          caseNumber,
          message: "Unauthorized destination",
        });
      expect(forgedDestination.status).toBe(400);
      expect(sendSmsMock).not.toHaveBeenCalled();

      // A provider membership grants case-portal access but is not permission
      // to trigger lab-side case-update texts.
      const providerSession = await makeSession(providerUserAId);
      const providerAttempt = await request(appMod.default)
        .post("/api/send-case-update-text")
        .set("Authorization", `Bearer ${providerSession.access}`)
        .send({ caseNumber, message: "Not authorized" });
      expect(providerAttempt.status).toBe(404);
      expect(sendSmsMock).not.toHaveBeenCalled();

      const allowed = await request(appMod.default)
        .post("/api/send-case-update-text")
        .set("Authorization", `Bearer ${labSession.access}`)
        .send({
          providerPhone: "+15550000001",
          caseNumber,
          message: "Your case has been updated.",
        });
      expect(allowed.status).toBe(200);
      expect(sendSmsMock).toHaveBeenCalledWith(
        expect.objectContaining({
          to: "+15550000001",
          body: "Your case has been updated.",
        }),
      );
    });

    it("throttles case-update texts per authenticated user", async () => {
      const { db, users, organizationMemberships } = dbMod as any;
      const { sendSms } = await import("../lib/sms.js");
      const sendSmsMock = vi.mocked(sendSms);
      sendSmsMock.mockClear();

      const senderId = rid("sms_sender");
      await db.insert(users).values({
        id: senderId,
        username: `sms_${senderId}`,
        password: "x",
        userType: "lab",
      });
      registeredUserIds.push(senderId);
      await db.insert(organizationMemberships).values({
        id: rid("m"),
        labId: labOrgId,
        userId: senderId,
        role: "user",
        status: "active",
        joinedAt: new Date(),
      });

      const { access } = await makeSession(senderId);
      const caseNumber = await caseNumberFor(caseAId);
      for (let attempt = 0; attempt < 5; attempt++) {
        const response = await request(appMod.default)
          .post("/api/send-case-update-text")
          .set("Authorization", `Bearer ${access}`)
          .send({ caseNumber, message: `Update ${attempt}` });
        expect(response.status).toBe(200);
      }

      const limited = await request(appMod.default)
        .post("/api/send-case-update-text")
        .set("Authorization", `Bearer ${access}`)
        .send({ caseNumber, message: "One more update" });
      expect(limited.status).toBe(429);
      expect(limited.headers["retry-after"]).toBeDefined();
      expect(sendSmsMock).toHaveBeenCalledTimes(5);
    });
  });

  // ── claimProvider pending membership ──────────────────────────────────────

  it("claimProvider signup creates a pending join request instead of granting immediate access", async () => {
    const {
      db,
      users,
      organizations,
      organizationMemberships,
      organizationJoinRequests,
      cases: casesTable,
      userSessions,
    } = dbMod as any;

    // Create a lab + provider org with a known account number.
    const claimLabId = rid("lab");
    const claimProvOrgId = rid("prov");
    const claimLabOwnerId = rid("u");
    const claimAcct = rid("ACCT");
    registeredOrgIds.push(claimLabId, claimProvOrgId);
    registeredUserIds.push(claimLabOwnerId);

    await db.insert(users).values({ id: claimLabOwnerId, username: `clo_${claimLabOwnerId}`, password: "x", userType: "lab" });
    await db.insert(organizations).values([
      { id: claimLabId, type: "lab", name: rid("ClaimTestLab") },
      { id: claimProvOrgId, type: "provider", name: rid("ClaimPractice"), parentLabOrganizationId: claimLabId, accountNumber: claimAcct },
    ]);
    await db.insert(organizationMemberships).values({
      id: rid("m"), labId: claimLabId, userId: claimLabOwnerId, role: "owner", status: "active", approvedByUserId: claimLabOwnerId, joinedAt: new Date(),
    });

    // Create a case assigned to the provider org BEFORE the provider signs up.
    const { access: labAccess } = await makeSession(claimLabOwnerId);
    const caseR = await request(appMod.default)
      .post("/api/cases")
      .set("Authorization", `Bearer ${labAccess}`)
      .send({
        caseNumber: rid("CN"),
        labOrganizationId: claimLabId,
        providerOrganizationId: claimProvOrgId,
        patientFirstName: "ClaimPatient",
        patientLastName: "Test",
        doctorName: "Dr. Claim",
        status: "received",
      });
    expect(caseR.status).toBe(201);
    const claimCaseId = caseR.body.data.id as string;
    createdCaseIds.push(claimCaseId);

    // Provider signup can use the account number to identify the practice, but
    // only an administrator can approve the resulting join request.
    const uname = `cp${randomBytes(3).toString("hex")}`;
    const regR = await request(appMod.default)
      .post("/api/auth/register")
      .send({
        username: uname,
        password: "Sup3rSecret!",
        email: `${uname}@example.com`,
        userType: "provider",
        claimProvider: { labId: claimLabId, accountNumber: claimAcct },
        clientType: "desktop",
      });
    expect(regR.status).toBe(200);
    const claimUserId: string = regR.body.user?.id;
    expect(claimUserId).toBeTruthy();
    registeredUserIds.push(claimUserId);

    // Mark the account as email-verified so requireVerifiedAccount passes.
    // (New canonical accounts have a P-YYYY-N number and require at least one
    // verified contact before accessing PHI via the cases endpoint.)
    await db.update(users).set({ emailVerifiedAt: new Date() }).where(eq(users.id, claimUserId));

    const activeMemberships = await db
      .select()
      .from(organizationMemberships)
      .where(eq(organizationMemberships.userId, claimUserId));
    expect(activeMemberships).toHaveLength(0);

    const pendingRequests = await db
      .select()
      .from(organizationJoinRequests)
      .where(eq(organizationJoinRequests.userId, claimUserId));
    expect(pendingRequests).toHaveLength(1);
    expect(pendingRequests[0]?.labId).toBe(claimProvOrgId);
    expect(pendingRequests[0]?.status).toBe("pending");

    const claimSess = await makeSession(claimUserId);
    const listR = await request(appMod.default)
      .get("/api/cases/provider")
      .set("Authorization", `Bearer ${claimSess.access}`);
    expect(listR.status).toBe(403);

    // Cleanup — delete invoices (auto-created on case POST) before orgs.
    const { invoices } = dbMod as any;
    if (invoices) {
      await db.delete(invoices).where(eq(invoices.providerOrganizationId, claimProvOrgId));
    }
    await db.delete(casesTable).where(eq(casesTable.id, claimCaseId));
    await db.delete(userSessions).where(eq(userSessions.userId, claimUserId));
    await db.delete(organizationJoinRequests).where(eq(organizationJoinRequests.userId, claimUserId));
    await db.delete(organizationMemberships).where(eq(organizationMemberships.userId, claimUserId));
    await db.delete(organizationMemberships).where(eq(organizationMemberships.userId, claimLabOwnerId));
    await db.delete(organizations).where(eq(organizations.id, claimProvOrgId));
    await db.delete(organizations).where(eq(organizations.id, claimLabId));
    await db.delete(users).where(eq(users.id, claimLabOwnerId));
  });

